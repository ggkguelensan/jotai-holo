const ref = (source: string, anchor: string): SourceRef => ({ source, anchor });
function node(
  id: string,
  kind: GraphNode['kind'],
  label: string,
  source: string,
  anchor: string,
  x: number,
  y: number,
  group?: string,
): GraphNode {
  return {
    id,
    kind,
    label,
    refs: [ref(source, anchor)],
    position: [x, y],
    ...(group ? { group } : {}),
  };
}

